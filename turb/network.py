"""The network. One forward pass makes a whole velocity field: from noise alone (a sample), or from the current
field (a step of 0.1 time units).

    noise, current field or zeros, the body force, a sample/step flag      on the internal grid, N/2 per side
      -> space-to-depth by 4 -> U-Net (three levels, FiLM on log Re and the flag, noise in every block)
      -> a sample: two x2 upsampling stages and a 3x3 convolution to two velocity components
         a step:   a 1x1 convolution on the U-Net's last layer and depth-to-space
      -> a random element of the flow's symmetry group
      -> Fourier space: a learned smooth gain per wavevector, projection onto divergence-free fields, zero-padding
         to the solver grid.

A step comes in two kinds. The learned step adds its output to a learned multiple a(k) of the current field. The
transport step adds it, through a gate that training opens from zero, to the current field carried one interval
forward by transport.py, and reads that carried field as an extra input; a fixed gain per wavenumber shell, set
after training from long rollouts, comes last. The transport step with no network at all is transport_step() in
transport.py.
"""
import math, os
import torch
import torch.nn as nn
import torch.nn.functional as F
from .spectral import Grid, regrid
from .transport import Transport

WEIGHTS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "weights")


def conv(cin, cout, k=3):
    return nn.Conv2d(cin, cout, k, padding=k // 2, padding_mode="circular" if k > 1 else "zeros")


class Block(nn.Module):
    def __init__(self, cin, cout, cemb, noise_cond=False, step_noise=False):
        super().__init__()
        self.c1, self.c2 = conv(cin, cout), conv(cout, cout)
        self.film = nn.Linear(cemb, 2 * cout)
        self.skip = conv(cin, cout, 1) if cin != cout else nn.Identity()
        self.noise = nn.Parameter(torch.zeros(cout))                              # per-channel noise amplitude
        self.nfilm = nn.Linear(cemb, cout) if noise_cond else None                # ... modulated by Re and the flag
        self.noise_step = nn.Parameter(torch.zeros(cout)) if step_noise else None  # ... and scaled again in a step
        self.quiet_steps = False

    def forward(self, x, emb, step):
        h = F.silu(self.c1(x))
        sc, sh = self.film(emb).chunk(2, dim=-1)
        h = h * (1 + sc[:, :, None, None]) + sh[:, :, None, None]
        if not (step and self.quiet_steps):
            amp = self.noise.view(1, -1, 1, 1)
            if self.nfilm is not None:
                amp = amp * torch.exp(self.nfilm(emb))[:, :, None, None]
            if step and self.noise_step is not None:
                amp = amp * torch.exp(self.noise_step).view(1, -1, 1, 1)
            h = h + amp * torch.randn_like(h)
        return self.skip(x) + self.c2(F.silu(h))


class Gain(nn.Module):
    """a smooth real function of the wavevector, log Re and the sample/step flag"""

    def __init__(self, hidden=64):
        super().__init__()
        self.f = nn.Sequential(nn.Linear(5, hidden), nn.SiLU(), nn.Linear(hidden, hidden), nn.SiLU(), nn.Linear(hidden, 1))

    def forward(self, g, kref, lr, mode):
        feats = torch.stack([g.kx.abs(), g.ky.abs(), g.kmag], -1) / kref
        c = torch.tensor([float(lr), float(mode)], device=feats.device).expand(feats.shape[:-1] + (2,))
        return self.f(torch.cat([feats, c], -1)).squeeze(-1)


class Symmetry:
    """The 16 symmetries of Kolmogorov flow with forcing sin(4 y) x_hat, generated by the shift-reflection
    S: (u, v)(x, y) -> (-u, v)(-x, y + pi/4) and the rotation by pi, R: u(x, y) -> -u(-x, -y)."""
    size = 16

    def __init__(self, n, kf=4):
        self.shift = n // (2 * kf)

    @staticmethod
    def _flip(u, axis):
        return torch.flip(torch.roll(u, -1, dims=axis), dims=(axis,))            # index i -> -i mod N

    def apply(self, u, e, inverse=False):
        j, m = e % 8, e // 8
        if not inverse:
            if m:
                u = -self._flip(self._flip(u, -1), -2)
            for _ in range(j):
                v = torch.roll(self._flip(u, -1), -self.shift, dims=-2)
                u = torch.stack([-v[:, 0], v[:, 1]], 1)
        else:
            for _ in range(j):
                v = torch.roll(torch.stack([-u[:, 0], u[:, 1]], 1), self.shift, dims=-2)
                u = self._flip(v, -1)
            if m:
                u = -self._flip(self._flip(u, -1), -2)
        return u


class Generator(nn.Module):
    def __init__(self, n=256, width=(32, 64, 64), inner=0.5, re_ref=2000.0, uscale=1.0, emb="fourier",
                 memory=False, noise_cond=False, transport=False, zch=4, cemb=128, p=4):
        super().__init__()
        self.n, self.inner, self.p, self.zch = n, inner, p, zch
        self.re_ref, self.uscale, self.smooth_emb = re_ref, uscale, emb == "smooth"
        self.transport = Transport(cut="substep") if transport else None            # the base this correction was trained on
        self.emb = nn.Sequential(nn.Linear(2 if self.smooth_emb else 18, cemb), nn.SiLU(), nn.Linear(cemb, cemb), nn.SiLU())
        blk = lambda cin, cout: Block(cin, cout, cemb, noise_cond, step_noise=transport)
        self.inp = conv((zch + 5 + (2 if transport else 0)) * p * p, width[0])
        self.down = nn.ModuleList([blk(a, b) for a, b in zip((width[0],) + tuple(width[:-1]), width)])
        self.mid = blk(width[-1], width[-1])
        self.up = nn.ModuleList()
        c = width[-1]
        for w in reversed(width):
            self.up.append(blk(c + w, w))
            c = w
        self.ups = nn.ModuleList([blk(c, c // 2), blk(c // 2, c // 4)])            # the sample head, back to the grid
        self.out = conv(c // 4, 2)
        self.gain = Gain()
        self.mem = Gain() if memory else None                                      # a(k) of the learned step
        self.gate = Gain() if transport else None                                  # the transport step's gate
        self.step_head = conv(width[0], 2 * p * p, 1) if transport else None
        self.shell_gain = None                                                     # set by load(): calibrated after training
        if transport:
            for m in self.modules():
                if isinstance(m, Block):
                    m.quiet_steps = True                                           # these steps are deterministic
        self._grids = {}

    def grid(self, n, device):
        key = (n, str(device))
        if key not in self._grids:
            y = torch.arange(n, device=device) * (2 * math.pi / n)
            force = torch.zeros((2, n, n), device=device)
            force[0] = torch.sin(4 * y).view(n, 1)
            self._grids[key] = (Grid(n, device), force, Symmetry(n))
        return self._grids[key]

    def noise(self, batch, device="cpu", generator=None):
        m = int(round(self.n * self.inner))
        return torch.randn((batch, self.zch, m, m), device=device, generator=generator)

    def embed(self, lr, mode, B, device):
        lrt = torch.full((B, 1), float(lr), device=device)
        flag = torch.full((B, 1), float(mode), device=device)
        if self.smooth_emb:
            return self.emb(torch.cat([lrt, flag], 1))
        fr = torch.arange(1, 9, device=device, dtype=lrt.dtype).view(1, -1)
        return self.emb(torch.cat([torch.sin(lrt * fr * 0.5), torch.cos(lrt * fr * 0.5), lrt, flag], 1))

    def forward(self, z, re, cond=None, sym=None):
        """z: noise from self.noise(); re: Reynolds number; cond: the current spectral velocity (B, 2, N, N/2+1) for a
        step, None for a sample. Returns the spectral velocity on the solver grid."""
        B, n, p = z.shape[0], z.shape[-1], self.p
        N = self.n if cond is None else cond.shape[-2]
        (g, force, group), (gN, _, _) = self.grid(n, z.device), self.grid(N, z.device)
        step = cond is not None
        lr = math.log(float(re) / self.re_ref)
        e = int(torch.randint(group.size, (1,))) if sym is None else sym
        extra, base = [], None
        if step:
            cm = regrid(cond, n)                                    # the modes the internal grid holds
            c = group.apply(g.ifft(cm), e, inverse=True) / self.uscale
            base = cm
            if self.transport is not None:
                base = self.transport(cm, g, re)
                extra = [group.apply(g.ifft(base), e, inverse=True) / self.uscale]
                z = torch.zeros_like(z)
        else:
            c = torch.zeros((B, 2, n, n), device=z.device)
            if self.transport is not None:
                extra = [torch.zeros_like(c)]
        flag = torch.full((B, 1, n, n), float(step), device=z.device)
        x = torch.cat([z, c] + extra + [force.expand(B, 2, n, n), flag], 1)
        emb = self.embed(lr, float(step), B, z.device)
        h = self.inp(F.pixel_unshuffle(x, p))
        skips = []
        for i, b in enumerate(self.down):
            h = b(F.avg_pool2d(h, 2) if i else h, emb, step)
            skips.append(h)
        h = self.mid(h, emb, step)
        for j, b in enumerate(self.up):
            if j:
                h = F.interpolate(h, scale_factor=2, mode="nearest")
            h = b(torch.cat([h, skips[-1 - j]], 1), emb, step)
        if step and self.step_head is not None:
            u = F.pixel_shuffle(self.step_head(F.silu(h)), p)
        else:
            for b in self.ups:
                h = b(F.interpolate(h, scale_factor=2, mode="nearest"), emb, step)
            u = self.out(F.silu(h))
        u = group.apply(u * self.uscale, e)
        uh = g.fft(u) * torch.exp(self.gain(g, gN.kmax, lr, float(step)))
        if step:
            if self.transport is not None:
                uh = uh * self.gate(g, gN.kmax, lr, 1.0) * g.dealias0 + base
                if self.shell_gain is not None:
                    uh = uh * self.shell_gain.to(uh.device)[g.shell]
            else:
                uh = uh + 2.0 * torch.sigmoid(self.mem(g, gN.kmax, lr, 1.0)) * base
        return regrid(g.project(uh), N) * gN.dealias0

    def fields(self, uh):
        """physical velocity (B, 2, N, N) and vorticity (B, N, N) of a spectral velocity"""
        g = self.grid(uh.shape[-2], uh.device)[0]
        return g.ifft(uh), g.ifft(g.curl(uh))


MODELS = {"sampler": "sampler.pt", "learned-step": "learned-step.pt", "transport-step": "transport-step.pt"}


def load(name, device="cpu"):
    """name: 'sampler' (noise to field), 'learned-step' (a step with nothing built in; it also samples) or
    'transport-step' (transport plus a learned correction), or a path to a weights file."""
    path = os.path.join(WEIGHTS, MODELS[name]) if name in MODELS else name
    ck = torch.load(path, map_location=device, weights_only=True)
    net = Generator(**ck["config"]).to(device)
    net.load_state_dict(ck["state_dict"])
    if ck.get("shell_gain") is not None:
        net.shell_gain = ck["shell_gain"].float().to(device)
    return net.eval().requires_grad_(False)
